import pytest

from src.intelligence.ioc_comparison import ioc_matches


@pytest.mark.parametrize(
    "indicator,observed,expected",
    [
        (
            "http://example.test/shell.php",
            "http://example.test:80/shell.php",
            True,
        ),
        (
            "http://example.test/shell.php",
            "http://example.test:443/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "https://example.test:444/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "http://example.test/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "https://user@example.test/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "https://example.test:abc/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "https://example.test:99999/shell.php",
            False,
        ),
        (
            "https://example.test",
            "https://example.test/",
            True,
        ),
        (
            "https://example.test/shell.php",
            "https://EXAMPLE.TEST/shell.php",
            True,
        ),
        (
            "/shell.php",
            "/%73hell.php",
            True,
        ),
        (
            "/shell.php",
            "/shell%2Ephp",
            True,
        ),
        (
            "/shell.php",
            "/%2573hell.php",
            False,
        ),
        (
            "/shell.php",
            "/shell%2F.php",
            False,
        ),
        (
            "/shell.php",
            "/shell.php.backup",
            False,
        ),
        (
            "/shell.php?mode=1",
            "/shell.php?mode=2",
            False,
        ),
        (
            "/Shell.php",
            "/shell.php",
            False,
        ),
        (
            "https://example.test/shell.php",
            "https://example.test.attacker.test/shell.php",
            False,
        ),
        (
            "/shell.php",
            "/shell.php?x=1",
            True,
        ),
    ],
)
def test_core08_url_security_contract(
    indicator,
    observed,
    expected,
):
    assert ioc_matches(
        "url",
        indicator,
        observed,
    ) is expected
